// Cloudflare Pages `_headers` file for the static Expo Updates site, plus a
// small parser/validator so a published site can be checked after the fact.
// Format: https://developers.cloudflare.com/pages/configuration/headers/
export const MAX_HEADER_RULES = 100;
export const MAX_HEADER_LINE_LENGTH = 2000;
export const ASSETS_CACHE_CONTROL = "public, max-age=31536000, immutable";
export const MANIFEST_CACHE_CONTROL = "private, max-age=0";
export const DEFAULT_ASSETS_PATTERN = "/assets/*";

const PATH_PATTERN = /^\/[A-Za-z0-9._~\-/]*$/;
const ASSETS_PATTERN = /^\/[A-Za-z0-9._~\-/]*\/\*$|^\/\*$/;
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/;

export interface BuildHeadersInput {
  readonly manifestPath: string;
  readonly signatureHeader: string;
  readonly assetsPath?: string;
  /** Optional SFV dictionary for `expo-manifest-filters`; omitted when absent. */
  readonly manifestFilters?: string;
  /** Optional SFV dictionary for `expo-server-defined-headers`; omitted when absent. */
  readonly serverDefinedHeaders?: string;
  /** Opt-in only: Cloudflare may comma-join it with its own default. */
  readonly contentType?: string;
}

export interface HeaderRule {
  readonly path: string;
  readonly headers: readonly { readonly name: string; readonly value: string }[];
}

export interface HeadersValidation {
  readonly problems: readonly string[];
  /** The `expo-signature` value found for the manifest path, if any. */
  readonly signatureHeader: string | null;
}

function assertHeaderValue(name: string, value: string): void {
  if (value.trim() === "" || CONTROL_CHARS.test(value)) {
    throw new Error(`The ${name} header value is empty or contains control characters.`);
  }
}

function assertLineLength(name: string, value: string): void {
  const line = `  ${name}: ${value}`;
  if (line.length > MAX_HEADER_LINE_LENGTH) {
    throw new Error(
      `The ${name} header line is ${line.length} characters; Cloudflare allows ${MAX_HEADER_LINE_LENGTH}.`,
    );
  }
}

/** The `_headers` text. The manifest rule is an exact path; assets get a splat rule. */
export function buildHeadersFile(input: BuildHeadersInput): string {
  const assetsPath = input.assetsPath ?? DEFAULT_ASSETS_PATTERN;
  if (!PATH_PATTERN.test(input.manifestPath)) {
    throw new Error(`Invalid manifest path for _headers: ${input.manifestPath}`);
  }
  if (!ASSETS_PATTERN.test(assetsPath)) {
    throw new Error(`Invalid assets path pattern for _headers: ${assetsPath}`);
  }
  const manifestHeaders: [string, string][] = [
    ["expo-protocol-version", "1"],
    ["expo-sfv-version", "0"],
    ["cache-control", MANIFEST_CACHE_CONTROL],
    ["expo-signature", input.signatureHeader],
  ];
  const optional: [string, string | undefined][] = [
    ["expo-manifest-filters", input.manifestFilters],
    ["expo-server-defined-headers", input.serverDefinedHeaders],
    ["content-type", input.contentType],
  ];
  for (const [name, value] of optional) {
    if (value !== undefined) manifestHeaders.push([name, value]);
  }
  for (const [name, value] of manifestHeaders) {
    assertHeaderValue(name, value);
    assertLineLength(name, value);
  }
  const lines = [
    "# Generated by ota/publish.ts. Expo Updates protocol v1, static hosting.",
    "# The signature below covers the exact bytes of the manifest file.",
    input.manifestPath,
    ...manifestHeaders.map(([name, value]) => `  ${name}: ${value}`),
    "",
    "# Assets are named after their content hash, so they never change.",
    assetsPath,
    `  cache-control: ${ASSETS_CACHE_CONTROL}`,
  ];
  return `${lines.join("\n")}\n`;
}

/** Parses `_headers` into rules. Comments, blank lines and malformed lines are skipped. */
export function parseHeadersFile(text: string): HeaderRule[] {
  const rules: { path: string; headers: { name: string; value: string }[] }[] = [];
  for (const rawLine of text.split(/\r?\n/)) {
    if (rawLine.trim() === "" || rawLine.trimStart().startsWith("#")) continue;
    if (!/^\s/.test(rawLine)) {
      rules.push({ path: rawLine.trim(), headers: [] });
      continue;
    }
    const current = rules[rules.length - 1];
    const colon = rawLine.indexOf(":");
    if (current === undefined || colon === -1) continue;
    current.headers.push({
      name: rawLine.slice(0, colon).trim().toLowerCase(),
      value: rawLine.slice(colon + 1).trim(),
    });
  }
  return rules;
}

const OPTIONAL_SFV_HEADERS = ["expo-manifest-filters", "expo-server-defined-headers"] as const;

function checkManifestRule(rule: HeaderRule, problems: string[]): string | null {
  const values = new Map<string, string>();
  for (const { name, value } of rule.headers) {
    if (values.has(name)) {
      problems.push(`${rule.path}: header ${name} is set more than once.`);
    }
    values.set(name, value);
  }
  const expectEqual = (name: string, expected: string): void => {
    if (values.get(name) !== expected) {
      problems.push(`${rule.path}: ${name} must be "${expected}" (found ${values.get(name) ?? "none"}).`);
    }
  };
  expectEqual("expo-protocol-version", "1");
  expectEqual("expo-sfv-version", "0");
  if (values.get("cache-control") !== MANIFEST_CACHE_CONTROL) {
    problems.push(`${rule.path}: cache-control must be "${MANIFEST_CACHE_CONTROL}".`);
  }
  for (const name of OPTIONAL_SFV_HEADERS) {
    if (values.get(name) === "") problems.push(`${rule.path}: ${name} is present but empty.`);
  }
  const signature = values.get("expo-signature");
  if (signature === undefined || signature === "") {
    problems.push(`${rule.path}: expo-signature header is missing.`);
    return null;
  }
  return signature;
}

/** Checks a `_headers` text against the Expo Updates and Cloudflare requirements. */
export function validateHeadersFile(text: string, manifestPath: string): HeadersValidation {
  const problems: string[] = [];
  const rules = parseHeadersFile(text);
  if (rules.length > MAX_HEADER_RULES) {
    problems.push(`_headers has ${rules.length} rules; Cloudflare allows ${MAX_HEADER_RULES}.`);
  }
  if (text.split(/\r?\n/).some((line) => line.length > MAX_HEADER_LINE_LENGTH)) {
    problems.push(`_headers has a line over ${MAX_HEADER_LINE_LENGTH} characters.`);
  }
  const manifestRule = rules.find((rule) => rule.path === manifestPath);
  let signatureHeader: string | null = null;
  if (manifestRule === undefined) {
    problems.push(`_headers has no rule for ${manifestPath}.`);
  } else {
    signatureHeader = checkManifestRule(manifestRule, problems);
  }
  const hasImmutableAssets = rules.some(
    (rule) =>
      rule.path.endsWith("/*") &&
      rule.headers.some(
        (h) => h.name === "cache-control" && h.value === ASSETS_CACHE_CONTROL,
      ) &&
      rule.path !== manifestPath,
  );
  if (!hasImmutableAssets) {
    problems.push(`_headers has no assets rule with "cache-control: ${ASSETS_CACHE_CONTROL}" (immutable).`);
  }
  return { problems, signatureHeader };
}
